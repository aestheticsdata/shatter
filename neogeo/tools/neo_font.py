def stamp(rows, scale, top, shadow):
    """A glyph as {(x, y): colour} with its shadow `shadow` pixels down-right."""
    face = {
        (x * scale + dx, top + y * scale + dy)
        for y, row in enumerate(rows)
        for x, bit in enumerate(row)
        if bit == "#"
        for dx in range(scale)
        for dy in range(scale)
    }
    cells = {(x + shadow, y + shadow): SHADOW for x, y in face}
    cells.update({cell: FACE for cell in face})
    return cells


def glyph_tiles():
    """Every tile the HUD letters with, as (name, [8x8 cells per tile]).

    SMALL and TALL are a tile a glyph, sitting on the tile's left edge so the
    8 px grid gives them Silkscreen's open spacing. BIG is four tiles a glyph,
    top left, top right, bottom left, bottom right.
    """
    small = [stamp(SMALL[c], 1, 1, 1) for c in CHARSET]
    tall = [stamp(TALL[c], 1, 0, 1) for c in "0123456789"]
    big = []
    for c in CHARSET:
        cells = stamp(BIG[c], 2, 0, 2)
        for oy in (0, 8):
            for ox in (0, 8):
                big.append({(x - ox, y - oy): v for (x, y), v in cells.items() if 0 <= x - ox < 8 and 0 <= y - oy < 8})
    return [("SMALL", small), ("TALL", tall), ("BIG", big)]
